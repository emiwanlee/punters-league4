// ==================== NORMALIZE MATCH TEAM NAMES ====================

function normalizeMatchTeamName(name) {
    if (!name) return name;
    
    let clean = name.trim();
    
    // Check if exact mapping exists
    if (MATCH_TEAM_MAPPING[clean]) {
        return MATCH_TEAM_MAPPING[clean];
    }
    
    // Clean common suffixes
    clean = clean.replace(/ FC$/g, '');
    clean = clean.replace(/ F\.C\.$/g, '');
    clean = clean.replace(/ SC$/g, '');
    clean = clean.replace(/ S\.C\.$/g, '');
    clean = clean.replace(/ United$/g, 'Utd');
    clean = clean.replace(/ Utd$/g, '');
    clean = clean.replace(/ Athletic$/g, '');
    clean = clean.replace(/ \(C\)$/g, '');
    clean = clean.replace(/ \(A\)$/g, '');
    
    return clean.trim();
}

function normalizeMatchesData() {
    for (const [leagueName, matches] of Object.entries(matchesData)) {
        matchesData[leagueName] = matches.map(match => ({
            ...match,
            home: normalizeMatchTeamName(match.home),
            away: normalizeMatchTeamName(match.away)
        }));
    }
}

